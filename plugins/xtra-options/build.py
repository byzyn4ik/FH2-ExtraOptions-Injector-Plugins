import argparse
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT / "common"))
import build_common as bc  # noqa: E402

MOD_NAME = "Xtra Options"
INI_NAME = "XtraOptions.ini"
GAMES = {"fh2": "FORZA_GAME_FH2", "fh2ff": "FORZA_GAME_FH2FF"}


def c_bytes(name, hex_text):
    data = bytes.fromhex(hex_text)
    return f"static const unsigned char {name}[] = {{{', '.join(f'0x{b:02x}' for b in data)}}};\n", len(data)


def feature_data(folder, out):
    """obj/<feature>/feature_data.h from feature.json and patches.json."""
    feature = json.loads((folder / "feature.json").read_text(encoding="utf-8"))
    patches = json.loads((folder / "patches.json").read_text(encoding="utf-8"))
    groups = feature["groups"]
    lines = [f"// Generated by build.py from features/{folder.name}/. Do not edit.\n",
             f'#define FEATURE_NAME "{feature["name"]}"\n', f"#define FEATURE_GAME {GAMES[feature['game']]}\n",
             f"#define FEATURE_HAS_CODE {1 if feature.get('code') else 0}\n",
             f"#define FEATURE_HAS_CONTEXT {1 if feature.get('context') else 0}\n",
             "typedef struct {\n    const char *name;\n    const wchar_t *section, *key;\n    int enabled_by_default;\n"
             "    const ForzaPatch *patches;\n    uint32_t count;\n} FeatureGroup;\n"]
    tables = []
    for group in groups:
        members = [p for p in patches if p["runtime_group"] == group]
        if not members:
            sys.exit(f"features/{folder.name}: group {group} has no patches")
        entries = []
        for index, patch in enumerate(members):
            stem = f"{group.lower()}_{index}"
            text, size = c_bytes(stem + "_patched", patch["patched"])
            lines.append(text)
            names = []
            for a, accepted in enumerate(patch["accepted"]):
                text, length = c_bytes(f"{stem}_accepted_{a}", accepted)
                if length != size:
                    sys.exit(f"features/{folder.name}: {patch['id']}: accepted bytes of another length")
                lines.append(text)
                names.append(f"{stem}_accepted_{a}")
            if patch["original"] not in patch["accepted"] or patch["patched"] not in patch["accepted"]:
                sys.exit(f"features/{folder.name}: {patch['id']}: original and patched must be accepted")
            lines.append(f"static const unsigned char *const {stem}_accepted[] = {{{', '.join(names)}}};\n")
            entries.append(f'    {{"{patch["id"]}", 0x{patch["rva"]:x}u, {size}u, {stem}_patched, {stem}_accepted, '
                           f'{len(names)}u}},\n')
        lines.append(f"static const ForzaPatch {group.lower()}_patches[] = {{\n{''.join(entries)}}};\n")
        key = groups[group]
        tables.append(f'    {{"{group}", L"{key["section"]}", L"{key["key"]}", {int(key["default"])}, '
                      f"{group.lower()}_patches, {len(members)}u}},\n")
    lines.append(f"static const FeatureGroup kGroups[] = {{\n{''.join(tables)}}};\n")
    out.mkdir(parents=True, exist_ok=True)
    bc.write_if_changed(out / "feature_data.h", "".join(lines))
    return feature


def check_ini(features):
    """Every feature's keys are in mod/XtraOptions.ini, in their sections."""
    import configparser
    ini = configparser.ConfigParser()
    ini.optionxform = str
    ini.read(HERE / "mod" / INI_NAME, encoding="utf-8")
    for name, feature in features.items():
        for group, key in feature["groups"].items():
            if not ini.has_option(key["section"], key["key"]):
                sys.exit(f"mod/{INI_NAME}: no [{key['section']}] {key['key']} for {name} ({group})")
            if ini.getint(key["section"], key["key"]) != int(key["default"]):
                sys.exit(f"mod/{INI_NAME}: [{key['section']}] {key['key']} differs from {name}'s default")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--zig", help="zig.exe (0.15.2)")
    parser.add_argument("--output", type=Path, default=HERE / "out")
    parser.add_argument("--sdk", type=Path, default=Path(os.environ.get("FORZA_SDK") or
                                                         ROOT.parent / "forza-injector" / "sdk" / "include"))
    parser.add_argument("--test", action="store_true", help="run the offline tests after building")
    parser.add_argument("--game", type=Path, help="tests: the FH2 game folder (default ~/FH2)")
    options = parser.parse_args(argv)
    zig = bc.find_zig(options.zig)
    sdk = options.sdk.resolve()
    if not (sdk / "forza_patch.h").is_file():
        sys.exit(f"forza_injector's SDK not found at {sdk} (--sdk <forza-injector>/sdk/include)")
    output = options.output.resolve()
    mod = output / "mods" / MOD_NAME
    plugins = mod / "plugins"
    if mod.exists():
        shutil.rmtree(mod)
    plugins.mkdir(parents=True)
    version = bc.mod_version(HERE / "mod" / "mod.json")

    features = {}
    for folder in sorted(p for p in (HERE / "features").iterdir() if (p / "feature.json").is_file()):
        build = output / "obj" / folder.name
        feature = feature_data(folder, build)
        features[folder.name] = feature
        dll = feature["dll"]
        bc.version_rc(build / "version.rc", version, dll, f"Xtra Options: {feature['name']} (forza_injector plugin)",
                      "Xtra Options")
        code = [folder / name for name in feature.get("code", [])]  # the feature's own C files, if any
        bc.run([zig, "cc", "-target", "x86_64-windows-gnu", "-std=c11", "-O2", "-Wall", "-Wextra", "-Werror",
                "-Wno-missing-field-initializers", "-fno-sanitize=all", "-DUNICODE", "-D_UNICODE",
                "-I", build, "-I", HERE / "src", "-I", sdk, "-shared", "-s", HERE / "src" / "patch_feature.c", *code,
                build / "version.rc", "-Wl,--out-implib," + str(build / "plugin.lib"), "-o", plugins / dll])
    check_ini(features)
    if options.test:
        for name, feature in features.items():
            for index, test in enumerate(feature.get("tests", [])):
                executable = output / "tests" / (name + "-" + str(index) + ".exe")
                executable.parent.mkdir(parents=True, exist_ok=True)
                bc.run([zig, "cc", "-target", "x86_64-windows-gnu", "-std=c11", "-O2",
                        "-Wall", "-Wextra", "-Werror", "-I", sdk, "-I", HERE / "src",
                        HERE / "features" / name / test, "-o", executable])
                bc.run([executable])

    # The remaining, coupled Extra Options hooks are an optional FH2 runtime
    # provider. The injector itself no longer links any of this game code.
    bc.run([sys.executable, HERE / "runtime" / "src" / "build.py", zig,
            "--azimuth", "--sdk", sdk, "--output", plugins / "XtraRuntime.dll",
            "--build-dir", output / "obj" / "runtime"])
    shutil.copy2(HERE / "mod" / "XtraRuntime.ini", plugins / "XtraRuntime.ini")

    # Keep a test build separate from the shipped module: tests exercise the
    # native patch transaction against mapped copies of the real game.
    if options.test:
        bc.run([sys.executable, HERE / "runtime" / "src" / "build.py", zig,
                "--azimuth", "--test", "--sdk", sdk,
                "--output", output / "tests" / "XtraRuntime.dll",
                "--build-dir", output / "obj" / "runtime-test"])

    # Xtra Features, as it is.
    xtra = output / "obj" / "xtra-features"
    subprocess.run([sys.executable, str(ROOT / "plugins" / "xtra-features" / "build.py"), "--zig", str(zig),
                    "--output", str(xtra)], check=True)
    for name in ("XtraFeatures.dll", "XtraFeatures.ini"):
        shutil.copy2(xtra / "mods" / "Xtra Features" / "plugins" / name, plugins / name)

    for stale in plugins.glob("*.lib"):
        stale.unlink()
    shutil.copy2(HERE / "mod" / "mod.json", mod / "mod.json")
    shutil.copy2(HERE / "mod" / INI_NAME, plugins / INI_NAME)
    for path in sorted(plugins.iterdir()):
        print(path)
    if options.test:
        command = [sys.executable, str(HERE / "tests" / "run_tests.py"), "--output", str(output), "--sdk", str(sdk)]
        if options.game:
            command += ["--game", str(options.game)]
        subprocess.run(command, check=True)
        command = [sys.executable, str(HERE / "runtime" / "tests" / "run_tests.py"),
                   "--output", str(output), "--sdk", str(sdk)]
        if options.game:
            command += ["--game", str(options.game)]
        subprocess.run(command, check=True)


if __name__ == "__main__":
    main()
