"""Build Xtra Options: Extra Options' features as forza_injector plugins, plus Xtra Features.

Usage: py plugins/xtra-options/build.py [--zig <zig.exe>] [--output out] [--sdk <forza-injector/sdk/include>]
                                        [--test] [--game <folder>]
(the top-level build.py runs it with --output out/build/xtra-options)

One mod folder, one INI:
  <output>/mods/Xtra Options/mod.json
  <output>/mods/Xtra Options/plugins/XtraOptions.ini      every feature's keys (Extra Options' names)
  <output>/mods/Xtra Options/plugins/<Feature>.dll        one per features/<feature>/ (feature.json + patches.json)
  <output>/mods/Xtra Options/plugins/XtraFeatures.dll     Xtra Features, built from plugins/xtra-features unchanged
  <output>/mods/Xtra Options/plugins/XtraFeatures.ini
Byte-patch features share src/patch_feature.c; build.py writes each one's
patch tables (obj/<feature>/feature_data.h) from its patches.json. --sdk is
forza_injector's sdk/include (default: the FORZA_SDK environment variable,
else ../forza-injector beside this repository). --test runs tests/run_tests.py. Nothing is installed.
Zig 0.15.2: --zig, else the ZIG environment variable, else zig on PATH.
"""
